/* Q3: Import Q2.d GLB unchanged. WebXR select = controller trigger press. */
(async () => {
 const canvas=document.getElementById('view'), status=document.getElementById('status');
 const engine=new BABYLON.Engine(canvas,true), scene=new BABYLON.Scene(engine);
 scene.clearColor=new BABYLON.Color4(.07,.10,.14,1);
 const camera=new BABYLON.ArcRotateCamera('preview',Math.PI/2+.35,1.2,2.3,new BABYLON.Vector3(0,.56,0),scene);camera.attachControl(canvas,true);
 new BABYLON.HemisphericLight('light',new BABYLON.Vector3(0,1,0),scene);
 engine.runRenderLoop(()=>scene.render());window.addEventListener('resize',()=>engine.resize());
 try {
  const result=await BABYLON.SceneLoader.ImportMeshAsync('', '../Q2/d/', 'rob.glb',scene);
  const placement=new BABYLON.TransformNode('AR placement',scene);
  result.meshes.filter(m=>!m.parent).forEach(m=>m.parent=placement);
  placement.scaling.setAll(.4);
  const names=['Blink','Surprise','Walk'];
  const clips=names.map(name=>result.animationGroups.find(g=>g.name===name));
  if(clips.some(c=>!c))throw new Error('Missing clips: '+result.animationGroups.map(g=>g.name).join(', '));
  let index=-1;
  function resetPose(){
   result.animationGroups.forEach(g=>{g.stop();g.reset();});
   // All morph weights return to neutral when switching between independent clips.
   result.meshes.forEach(m=>{const mm=m.morphTargetManager;if(mm)for(let j=0;j<mm.numTargets;j++)mm.getTarget(j).influence=0;});
  }
  function next(){resetPose();index=(index+1)%3;clips[index].start(true,1);status.textContent='Action '+(index+1)+'/3: '+names[index];}
  document.getElementById('next').onclick=next;
  document.getElementById('reset').onclick=()=>{resetPose();if(index>=0)clips[index].start(true,1);};
  window.addEventListener('keydown',e=>{if(e.code==='Space'&&!e.repeat){e.preventDefault();next();}});
  next();
  if(navigator.xr && await navigator.xr.isSessionSupported('immersive-ar')){
   const xr=await scene.createDefaultXRExperienceAsync({uiOptions:{sessionMode:'immersive-ar',referenceSpaceType:'local-floor'},disableTeleportation:true});
   xr.baseExperience.sessionManager.onXRSessionInit.add(session=>{
    // 'select' is generated by the primary controller trigger; one event per press.
    session.addEventListener('select',next);
    // Wait for a tracked camera pose instead of assuming a world forward axis.
    xr.baseExperience.sessionManager.onXRFrameObservable.addOnce(()=>{
     const head=xr.baseExperience.camera;
     const forward=head.getForwardRay().direction.clone();forward.y=0;
     if(forward.lengthSquared()<1e-6)forward.set(0,0,1);
     forward.normalize();
     placement.position.set(head.position.x+forward.x*1.8,0,head.position.z+forward.z*1.8);
     // Face the viewer after Babylon converts the imported coordinate system.
     placement.rotation.y=Math.atan2(-forward.x,-forward.z);
    });
   });
   xr.baseExperience.onStateChangedObservable.add(state=>{
    if(state===BABYLON.WebXRState.NOT_IN_XR){placement.position.set(0,0,0);placement.rotation.y=0;}
   });
  }else status.textContent+=' | Desktop preview: immersive AR unavailable';
  window.assignmentDemo={scene,result,next,clips};
 }catch(error){status.textContent='Error: '+error.message;console.error(error);}
})();
